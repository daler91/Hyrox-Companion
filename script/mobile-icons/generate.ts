/**
 * Icons drawn filled as well as stroked, in the tint: the on-state of a
 * toggle, as the web's `fill-current` (a favourite's star).
 */
export const FILLED: ReadonlySet<string> = new Set(["StarFilled"]);

export type IconNode = [tag: string, attrs: Record<string, string>];

const num = (attrs: Record<string, string>, key: string, fallback = 0): number => {
  const value = attrs[key];
  return value === undefined ? fallback : Number(value);
};

/** SVG path data for one Lucide shape element. */
export function toPathData([tag, attrs]: IconNode): string {
  switch (tag) {
    case "path":
      return attrs.d;
    case "line":
      return `M${num(attrs, "x1")} ${num(attrs, "y1")}L${num(attrs, "x2")} ${num(attrs, "y2")}`;
    case "polyline":
    case "polygon": {
      const points = attrs.points.trim().split(/[\s,]+/).map(Number);
      const pairs: string[] = [];
      for (let i = 0; i + 1 < points.length; i += 2) pairs.push(`${points[i]} ${points[i + 1]}`);
      return `M${pairs.join("L")}${tag === "polygon" ? "Z" : ""}`;
    }
    case "circle":
      return ellipse(num(attrs, "cx"), num(attrs, "cy"), num(attrs, "r"), num(attrs, "r"));
    case "ellipse":
      return ellipse(num(attrs, "cx"), num(attrs, "cy"), num(attrs, "rx"), num(attrs, "ry"));
    case "rect": {
      const x = num(attrs, "x");
      const y = num(attrs, "y");
      const w = num(attrs, "width");
      const h = num(attrs, "height");
      const rx = Math.min(num(attrs, "rx", num(attrs, "ry")), w / 2);
      const ry = Math.min(num(attrs, "ry", rx), h / 2);
      if (rx === 0 || ry === 0) return `M${x} ${y}H${x + w}V${y + h}H${x}Z`;
      return (
        `M${x + rx} ${y}H${x + w - rx}A${rx} ${ry} 0 0 1 ${x + w} ${y + ry}` +
        `V${y + h - ry}A${rx} ${ry} 0 0 1 ${x + w - rx} ${y + h}` +
        `H${x + rx}A${rx} ${ry} 0 0 1 ${x} ${y + h - ry}` +
        `V${y + ry}A${rx} ${ry} 0 0 1 ${x + rx} ${y}Z`
      );
    }
    default:
      throw new Error(`Unsupported Lucide element <${tag}>`);
  }
}

function ellipse(cx: number, cy: number, rx: number, ry: number): string {
  return `M${cx - rx} ${cy}A${rx} ${ry} 0 1 0 ${cx + rx} ${cy}A${rx} ${ry} 0 1 0 ${cx - rx} ${cy}Z`;
}

/** The Kotlin source for [icons] (Kotlin name → Lucide nodes). */
export function generateIconsKotlin(icons: Readonly<Record<string, IconNode[]>>, lucideVersion: string): string {
  const entries = Object.keys(icons)
    .sort(byCodeUnit)
    .map((name) => {
      const paths = icons[name].map((node) => `            "${toPathData(node)}",`).join("\n");
      const filled = FILLED.has(name) ? "\n            filled = true," : "";
      return `    val ${name}: ImageVector by lazy {\n        lucide(\n            "${name}",\n${paths}${filled}\n        )\n    }`;
    })
    .join("\n\n");
  return `// Generated by script/mobile-icons from lucide-react ${lucideVersion}. Do not edit: run \`pnpm mobile:icons\`.
// Lucide is ISC-licensed; the licence ships in composeResources/files/licenses/LICENSE-lucide.txt.
package com.fitai.coach.ui.icons.generated

import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.SolidColor
import androidx.compose.ui.graphics.StrokeCap
import androidx.compose.ui.graphics.StrokeJoin
import androidx.compose.ui.graphics.vector.ImageVector
import androidx.compose.ui.graphics.vector.PathParser
import androidx.compose.ui.unit.dp

/** The Lucide icons the app uses: 24 dp, 1.5 dp stroke, tinted by Icon's colour (brand kit §8). A filled icon is also filled in that colour. */
object LucideIcons {
${entries}
}

private fun lucide(name: String, vararg paths: String, filled: Boolean = false): ImageVector = ImageVector.Builder(
    name = name,
    defaultWidth = 24.dp,
    defaultHeight = 24.dp,
    viewportWidth = 24f,
    viewportHeight = 24f,
).apply {
    for (path in paths) {
        addPath(
            pathData = PathParser().parsePathString(path).toNodes(),
            fill = if (filled) SolidColor(Color.Black) else null,
            stroke = SolidColor(Color.Black),
            strokeLineWidth = 1.5f,
            strokeLineCap = StrokeCap.Round,
            strokeLineJoin = StrokeJoin.Round,
        )
    }
}.build()
`;
}
