/**
 * Generates the native app's exercise catalogue, Kotlin source in
 * mobile/core's com.fitai.coach.core.exercises.generated, from the
 * TypeScript tables the server and the web read:
 *
 *  - shared/schema/exercises.ts: EXERCISE_DEFINITIONS (label, category and
 *    fields; muscleGroups is not needed on the device) and
 *    EXERCISE_NAME_ALIASES;
 *  - shared/exerciseEquipment.ts: EXERCISE_EQUIPMENT, IMPLEMENT_OVERRIDES,
 *    BARBELL_STEPS, INCREMENTS and LOADED_IMPLEMENTS.
 *
 * The hand-ported functions in com.fitai.coach.core.exercises
 * (normalizeExerciseName, implementFor, loadIncrement, suggestNextTarget, …)
 * read these, so the app's catalogue is the server's, entry for entry and in
 * the same order (docs/mobile-shared-logic.md, open question 2).
 *
 * Every map keeps the TypeScript iteration order. Each is filled by private
 * functions of at most CHUNK entries, so no single JVM method approaches the
 * 64 KB bytecode limit as the catalogue grows.
 */
import {
  BARBELL_STEPS,
  EXERCISE_EQUIPMENT,
  IMPLEMENT_OVERRIDES,
  type ImplementSteps,
  INCREMENTS,
  LOADED_IMPLEMENTS,
} from "@shared/exerciseEquipment";
import { EXERCISE_DEFINITIONS, EXERCISE_NAME_ALIASES } from "@shared/schema/exercises";

export const KOTLIN_PACKAGE = "com.fitai.coach.core.exercises.generated";
/** Where the hand-written types the data is built from live. */
const TYPES_PACKAGE = "com.fitai.coach.core.exercises";
/** The generated file, relative to the repository root. */
export const CATALOGUE_PATH = [
  "mobile/core/src/commonMain/kotlin",
  ...KOTLIN_PACKAGE.split("."),
  "ExerciseCatalogue.kt",
].join("/");

const HEADER = [
  "// Generated by script/kotlin-catalogue from shared/schema/exercises.ts and",
  "// shared/exerciseEquipment.ts. Do not edit: run `pnpm mobile:catalogue`.",
].join("\n");

/** Entries per initialiser function. */
export const CHUNK = 50;

/** The TypeScript tables the catalogue is generated from. */
export interface CatalogueSource {
  readonly definitions: Readonly<
    Record<
      string,
      { readonly label: string; readonly category: string; readonly fields: readonly string[] }
    >
  >;
  readonly aliases: Readonly<Record<string, string>>;
  readonly equipment: Readonly<Partial<Record<string, readonly string[]>>>;
  readonly implementOverrides: Readonly<Partial<Record<string, string>>>;
  readonly barbellSteps: ImplementSteps;
  readonly increments: ReadonlyMap<string, ImplementSteps>;
  readonly loadedImplements: readonly string[];
}

export const CATALOGUE_SOURCE: CatalogueSource = {
  definitions: EXERCISE_DEFINITIONS,
  aliases: EXERCISE_NAME_ALIASES,
  equipment: EXERCISE_EQUIPMENT,
  implementOverrides: IMPLEMENT_OVERRIDES,
  barbellSteps: BARBELL_STEPS,
  increments: INCREMENTS,
  loadedImplements: LOADED_IMPLEMENTS,
};

/** A Kotlin string literal, with anything outside printable ASCII escaped. */
export function kotlinString(value: string): string {
  let out = '"';
  for (const unit of value.split("")) {
    const code = unit.charCodeAt(0);
    if (unit === "\\" || unit === '"' || unit === "$") out += `\\${unit}`;
    else if (code >= 0x20 && code < 0x7f) out += unit;
    else out += `\\u${code.toString(16).padStart(4, "0")}`;
  }
  return `${out}"`;
}

/** A Kotlin Double literal that parses back to exactly `value`. */
export function kotlinDouble(value: number): string {
  if (!Number.isFinite(value)) throw new Error(`Not a finite number: ${value}`);
  const text = String(value);
  return /[.e]/.test(text) ? text : `${text}.0`;
}

/** `dumbbell` → `Implement.Dumbbell`. The Kotlin enum is hand-written; a new TS implement fails to compile until it is added. */
function implement(value: string): string {
  if (!/^[a-z]+(_[a-z]+)*$/.test(value)) throw new Error(`Unexpected implement name: ${value}`);
  const pascal = value
    .split("_")
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join("");
  return `Implement.${pascal}`;
}

function stringList(values: readonly string[]): string {
  return `listOf(${values.map(kotlinString).join(", ")})`;
}

function steps(value: ImplementSteps): string {
  return `ImplementSteps(kg = ${kotlinDouble(value.kg)}, lbs = ${kotlinDouble(value.lbs)})`;
}

function kdoc(lines: readonly string[]): string {
  return ["/**", ...lines.map((line) => ` * ${line}`.trimEnd()), " */"].join("\n");
}

interface MapDecl {
  readonly name: string;
  readonly visibility: "public" | "internal";
  readonly doc: readonly string[];
  readonly keyType: string;
  readonly valueType: string;
  /** Kotlin key and value expressions, in iteration order. */
  readonly entries: readonly (readonly [string, string])[];
}

/** `EXERCISE_DEFINITIONS` → `exerciseDefinitions`. */
function camel(screaming: string): string {
  return screaming
    .toLowerCase()
    .replaceAll(/_([a-z])/g, (_, letter: string) => letter.toUpperCase());
}

/** A map property filled in insertion order by CHUNK-sized private extension functions. */
function chunkedMap(decl: MapDecl): string {
  const fill = camel(decl.name);
  const parts: string[] = [];
  for (let start = 0; start < decl.entries.length; start += CHUNK) {
    parts.push(
      [
        `private fun MutableMap<${decl.keyType}, ${decl.valueType}>.${fill}${parts.length}() {`,
        ...decl.entries
          .slice(start, start + CHUNK)
          .map(([key, value]) => `    put(${key}, ${value})`),
        "}",
      ].join("\n"),
    );
  }
  const calls = parts.map((_, index) => `    ${fill}${index}()`);
  const property = [
    kdoc(decl.doc),
    `${decl.visibility} val ${decl.name}: Map<${decl.keyType}, ${decl.valueType}> = buildMap(${decl.entries.length}) {`,
    ...calls,
    "}",
  ].join("\n");
  return [property, ...parts].join("\n\n");
}

/** The content of ExerciseCatalogue.kt. */
export function generateExerciseCatalogue(source: CatalogueSource = CATALOGUE_SOURCE): string {
  const definitionEntries = Object.entries(source.definitions);
  const aliasEntries = Object.entries(source.aliases);
  for (const [alias, target] of aliasEntries) {
    if (!Object.hasOwn(source.definitions, target))
      throw new Error(`Alias ${alias} points at unknown exercise ${target}`);
  }
  const equipmentEntries = Object.entries(source.equipment).filter(
    (entry): entry is [string, readonly string[]] => entry[1] !== undefined,
  );
  const overrideEntries = Object.entries(source.implementOverrides).filter(
    (entry): entry is [string, string] => entry[1] !== undefined,
  );

  const sections = [
    chunkedMap({
      name: "EXERCISE_DEFINITIONS",
      visibility: "public",
      doc: [
        "`EXERCISE_DEFINITIONS` (shared/schema/exercises.ts): every canonical exercise name, in the",
        "TypeScript order, with its label, category and logged fields.",
      ],
      keyType: "String",
      valueType: "ExerciseDefinition",
      entries: definitionEntries.map(([name, definition]) => [
        kotlinString(name),
        `ExerciseDefinition(${kotlinString(definition.label)}, ${kotlinString(definition.category)}, ${stringList(definition.fields)})`,
      ]),
    }),
    chunkedMap({
      name: "EXERCISE_NAME_ALIASES",
      visibility: "public",
      doc: [
        "`EXERCISE_NAME_ALIASES` (shared/schema/exercises.ts): a slug that is not a canonical name →",
        "the canonical name it stands for.",
      ],
      keyType: "String",
      valueType: "String",
      entries: aliasEntries.map(([alias, target]) => [kotlinString(alias), kotlinString(target)]),
    }),
    chunkedMap({
      name: "EXERCISE_EQUIPMENT",
      visibility: "public",
      doc: [
        "`EXERCISE_EQUIPMENT` (shared/exerciseEquipment.ts): the equipment an exercise needs, any one",
        "listed item being enough. An exercise absent from the map needs nothing a filter can rule out.",
      ],
      keyType: "String",
      valueType: "List<String>",
      entries: equipmentEntries.map(([name, items]) => [kotlinString(name), stringList(items)]),
    }),
    chunkedMap({
      name: "IMPLEMENT_OVERRIDES",
      visibility: "internal",
      doc: [
        "`IMPLEMENT_OVERRIDES` (shared/exerciseEquipment.ts): how an exercise is loaded where the",
        "equipment table cannot say.",
      ],
      keyType: "String",
      valueType: "Implement",
      entries: overrideEntries.map(([name, value]) => [kotlinString(name), implement(value)]),
    }),
    [
      kdoc([
        "`BARBELL_STEPS` (shared/exerciseEquipment.ts): plate steps, the fallback for any implement.",
      ]),
      `internal val BARBELL_STEPS: ImplementSteps = ${steps(source.barbellSteps)}`,
    ].join("\n"),
    chunkedMap({
      name: "INCREMENTS",
      visibility: "internal",
      doc: [
        "`INCREMENTS` (shared/exerciseEquipment.ts): the smallest jump each implement allows, per unit.",
      ],
      keyType: "Implement",
      valueType: "ImplementSteps",
      entries: [...source.increments].map(([name, value]) => [
        implement(name),
        value === source.barbellSteps ? "BARBELL_STEPS" : steps(value),
      ]),
    }),
    [
      kdoc([
        "`LOADED_IMPLEMENTS` (shared/exerciseEquipment.ts): the order `implementFor` tries an",
        "exercise's equipment in.",
      ]),
      `internal val LOADED_IMPLEMENTS: List<Implement> = listOf(${source.loadedImplements.map(implement).join(", ")})`,
    ].join("\n"),
  ];

  const imports = ["ExerciseDefinition", "Implement", "ImplementSteps"].map(
    (type) => `import ${TYPES_PACKAGE}.${type}`,
  );
  return `${[HEADER, `package ${KOTLIN_PACKAGE}`, imports.join("\n"), ...sections].join("\n\n")}\n`;
}
