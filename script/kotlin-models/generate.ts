// Schema → Kotlin type
// ---------------------------------------------------------------------------

const PRIMITIVE = {
  string: { kotlin: "String", serializer: "String.serializer()" },
  int: { kotlin: "Int", serializer: "Int.serializer()" },
  long: { kotlin: "Long", serializer: "Long.serializer()" },
  double: { kotlin: "Double", serializer: "Double.serializer()" },
  boolean: { kotlin: "Boolean", serializer: "Boolean.serializer()" },
  json: { kotlin: "JsonElement", serializer: "JsonElement.serializer()" },
  jsonObject: { kotlin: "JsonObject", serializer: "JsonObject.serializer()" },
} as const;

const prim = (p: (typeof PRIMITIVE)[keyof typeof PRIMITIVE], nullable = false): KType => ({ ...p, nullable });

class Generator {
  private readonly schemas: Record<string, Schema>;
  /** How each component is referenced: its name, or for an alias its target's serializer. */
  private readonly componentTypes = new Map<string, KType>();

  constructor(private readonly doc: OpenApiDocument) {
    this.schemas = doc.components?.schemas ?? {};
  }

  private refName(schema: Schema): string | undefined {
    const ref = schema.$ref;
    if (typeof ref !== "string") return undefined;
    const name = /^#\/components\/schemas\/(.+)$/.exec(ref)?.[1];
    if (!name || !(name in this.schemas)) throw new Error(`Unresolved $ref ${ref}`);
    return name;
  }

  private resolve(schema: Schema): Schema {
    const name = this.refName(schema);
    return name ? this.resolve(this.schemas[name] ?? {}) : schema;
  }

  /** The properties and required list of an object-like schema, following refs and allOf. */
  private objectParts(schema: Schema): { properties: Record<string, Schema>; required: Set<string>; doc?: string } {
    const s = this.resolve(schema);
    const properties: Record<string, Schema> = {};
    const required = new Set<string>();
    if (Array.isArray(s.allOf)) {
      for (const part of s.allOf as Schema[]) {
        const inner = this.objectParts(part);
        Object.assign(properties, inner.properties);
        inner.required.forEach((r) => required.add(r));
      }
    }
    if (isObject(s.properties)) Object.assign(properties, s.properties);
    if (Array.isArray(s.required)) (s.required as string[]).forEach((r) => required.add(r));
    return { properties, required, doc: typeof s.description === "string" ? s.description : undefined };
  }

  /** allOf entries that only add a description or nullability to a single ref. */
  private nullableRefAllOf(schema: Schema): { ref: Schema; nullable: boolean } | undefined {
    if (!Array.isArray(schema.allOf)) return undefined;
    const parts = schema.allOf as Schema[];
    const refs = parts.filter((p) => typeof p.$ref === "string");
    const others = parts.filter((p) => typeof p.$ref !== "string");
    if (refs.length !== 1 || others.some((o) => o.properties !== undefined || o.type !== undefined)) return undefined;
    const nullable = schema.nullable === true || others.some((o) => o.nullable === true);
    return { ref: refs[0], nullable };
  }

  private integerType(schema: Schema): KType {
    const min = typeof schema.minimum === "number" ? schema.minimum : undefined;
    const max = typeof schema.maximum === "number" ? schema.maximum : undefined;
    const fitsInt = min !== undefined && max !== undefined && min >= -2147483648 && max <= 2147483647;
    // Unbounded integers (counts, ids, milliseconds) get Long: an Int that
    // overflows on a large value would be a silent decoding failure.
    return prim(fitsInt || schema.format === "int32" ? PRIMITIVE.int : PRIMITIVE.long);
  }

  /**
   * The Kotlin type for `schema`. Inline objects and enums become declarations
   * named `name`, returned for the caller to place (nested in the owning class,
   * or top level). `owner` is the dotted path of the enclosing class, used to
   * qualify nested names.
   */
  typeOf(schema: Schema, name: string, owner: string, context: Context): { type: KType; decls: Decl[] } {
    const qualified = owner ? `${owner}.${name}` : name;
    const nullable = schema.nullable === true;
    const done = (type: KType, decls: Decl[] = []) => ({ type: { ...type, nullable: type.nullable || nullable }, decls });

    const ref = this.refName(schema);
    if (ref) return done(this.componentType(ref));

    const refAllOf = this.nullableRefAllOf(schema);
    if (refAllOf) {
      const inner = this.typeOf(refAllOf.ref, name, owner, context);
      return { type: { ...inner.type, nullable: inner.type.nullable || refAllOf.nullable }, decls: inner.decls };
    }

    if (Array.isArray(schema.allOf)) {
      // An extension (`.extend` of a registered schema) or a merge of objects: one flattened class.
      const parts = this.objectParts(schema);
      return done(...this.objectType(parts.properties, parts.required, schema, name, qualified, context));
    }

    const union = (schema.oneOf ?? schema.anyOf) as Schema[] | undefined;
    if (Array.isArray(union)) {
      const resolved = union.map((v) => this.resolve(v));
      const wholeNumbers = (v: Schema) =>
        v.type === "number" && Array.isArray(v.enum) && (v.enum as unknown[]).every((e) => e === null || Number.isInteger(e));
      if (resolved.every((v) => wholeNumbers(v))) return done(prim(PRIMITIVE.int));
      if (resolved.every((v) => v.type === "integer")) return done(prim(PRIMITIVE.long));
      if (resolved.every((v) => v.type === "number" || v.type === "integer")) return done(prim(PRIMITIVE.double));
      return done(prim(PRIMITIVE.json));
    }

    if (Array.isArray(schema.enum)) {
      const values = schema.enum as unknown[];
      if (schema.type === "boolean") return done(prim(PRIMITIVE.boolean));
      if (schema.type === "integer") return done(this.integerType(schema));
      // A numeric enum of whole numbers (meals per day: 3, 4, 5) is an integer;
      // a Double would be sent as 3.0.
      if (schema.type === "number") {
        const whole = values.every((v) => v === null || (typeof v === "number" && Number.isInteger(v)));
        return done(prim(whole ? PRIMITIVE.int : PRIMITIVE.double));
      }
      const strings = values.filter((v): v is string => typeof v === "string");
      // A single-value enum is a zod literal (`code: "VALIDATION_ERROR"`): just the string.
      if (strings.length <= 1) return done(prim(PRIMITIVE.string));
      const decl: Decl = { kind: "enum", name, doc: this.describe(schema), values: strings };
      return done({ kotlin: qualified, serializer: `${qualified}.serializer()`, nullable: false }, [decl]);
    }

    switch (schema.type) {
      case "string":
        return done(prim(PRIMITIVE.string));
      case "integer":
        return done(this.integerType(schema));
      case "number":
        return done(prim(PRIMITIVE.double));
      case "boolean":
        return done(prim(PRIMITIVE.boolean));
      case "array": {
        const item = this.typeOf(isObject(schema.items) ? schema.items : {}, `${name}Item`, owner, context);
        const kotlin = `List<${render(item.type)}>`;
        return done({ kotlin, serializer: `ListSerializer(${serializerOf(item.type)})`, nullable: false }, item.decls);
      }
      default:
        break;
    }

    if (schema.type === "object" || isObject(schema.properties)) {
      const properties = isObject(schema.properties) ? (schema.properties as Record<string, Schema>) : {};
      if (Object.keys(properties).length === 0) {
        const extra = schema.additionalProperties;
        if (isObject(extra) && Object.keys(extra).length > 0) {
          const value = this.typeOf(extra, `${name}Value`, owner, context);
          return done(
            { kotlin: `Map<String, ${render(value.type)}>`, serializer: `MapSerializer(String.serializer(), ${serializerOf(value.type)})`, nullable: false },
            value.decls,
          );
        }
        return done(extra === undefined ? prim(PRIMITIVE.jsonObject) : { kotlin: "Map<String, JsonElement>", serializer: "MapSerializer(String.serializer(), JsonElement.serializer())", nullable: false });
      }
      const required = new Set(Array.isArray(schema.required) ? (schema.required as string[]) : []);
      return done(...this.objectType(properties, required, schema, name, qualified, context));
    }

    // {} / z.unknown() / z.any(): any JSON value.
    return done(prim(PRIMITIVE.json));
  }

  private describe(schema: Schema): string | undefined {
    return typeof schema.description === "string" ? schema.description : undefined;
  }

  private objectType(
    properties: Record<string, Schema>,
    required: Set<string>,
    schema: Schema,
    name: string,
    qualified: string,
    context: Context,
  ): [KType, Decl[]] {
    const decl = this.classDecl(properties, required, name, qualified, context, this.describe(schema) ?? this.objectParts(schema).doc);
    return [{ kotlin: qualified, serializer: `${qualified}.serializer()`, nullable: false }, [decl]];
  }

  private classDecl(
    properties: Record<string, Schema>,
    required: Set<string>,
    name: string,
    qualified: string,
    context: Context,
    doc: string | undefined,
  ): Decl {
    const props: PropDecl[] = [];
    const nested: Decl[] = [];
    const usedNested = new Set<string>();
    const usedKotlin = new Set<string>();
    for (const [jsonName, propSchema] of Object.entries(properties)) {
      let nestedName = pascal(jsonName);
      while (usedNested.has(nestedName) || nestedName === name) nestedName = `${nestedName}Value`;
      usedNested.add(nestedName);
      const { type, decls } = this.typeOf(propSchema, nestedName, qualified, context);
      nested.push(...decls);
      let kotlinName = camel(jsonName);
      while (usedKotlin.has(kotlinName)) kotlinName = `${kotlinName}_`;
      usedKotlin.add(kotlinName);
      props.push({ jsonName, kotlinName, type, required: required.has(jsonName), doc: this.describe(this.resolveDoc(propSchema)) });
    }
    return { kind: "class", name, doc, context, props, nested };
  }

  /** A property's description may sit on the allOf wrapper or on the referenced component. */
  private resolveDoc(schema: Schema): Schema {
    if (typeof schema.description === "string") return schema;
    return {};
  }

  private readonly resolving = new Set<string>();
  /** Components declared as a class or enum; the rest are typealiases. */
  private readonly declaredAsType = new Set<string>();

  /** How a component is referenced, worked out on first use (an alias may point at a later one). */
  private componentType(name: string): KType {
    const known = this.componentTypes.get(name);
    if (known) return known;
    if (this.resolving.has(name)) {
      // A cycle through an alias; a class reference is just its name.
      return { kotlin: name, serializer: `${name}.serializer()`, nullable: false };
    }
    this.resolving.add(name);
    const type = this.componentReference(name, this.schemas[name] ?? {});
    this.resolving.delete(name);
    this.componentTypes.set(name, type);
    return type;
  }

  /** Declare every component. */
  components(contexts: Map<string, Context>): Map<string, Decl> {
    const names = Object.keys(this.schemas).sort();
    for (const name of names) this.componentType(name);
    const decls = new Map<string, Decl>();
    for (const name of names) {
      const schema = this.schemas[name] ?? {};
      const context = contexts.get(name) ?? "response";
      if (this.declaredAsType.has(name)) {
        const { decls: inner } = this.typeOf(this.unwrapComponent(schema), name, "", context);
        const top = inner.find((d) => d.name === name);
        if (!top) throw new Error(`Component ${name} produced no declaration`);
        decls.set(name, top);
      } else {
        const { type, decls: inner } = this.typeOf(schema, `${name}Value`, "", context);
        if (inner.length > 0) throw new Error(`Alias component ${name} declares types; give it a class shape`);
        decls.set(name, { kind: "alias", name, doc: this.describe(schema), target: type });
      }
    }
    return decls;
  }

  /** A component is declared without its own top-level nullability (refs carry it). */
  private unwrapComponent(schema: Schema): Schema {
    if (schema.nullable !== true) return schema;
    const { nullable: _nullable, ...rest } = schema;
    return rest;
  }

  private componentReference(name: string, schema: Schema): KType {
    const s = this.unwrapComponent(schema);
    const isEnum = Array.isArray(s.enum) && s.type === "string" && (s.enum as unknown[]).length > 1;
    const isObjectish =
      s.type === "object" && isObject(s.properties) && Object.keys(s.properties).length > 0 ||
      (Array.isArray(s.allOf) && !this.nullableRefAllOf(s));
    if (isEnum || isObjectish) {
      this.declaredAsType.add(name);
      return { kotlin: name, serializer: `${name}.serializer()`, nullable: false };
    }
    // Anything else is a typealias; refs use the alias name and the target's serializer.
    const target = this.typeOf(s, `${name}Value`, "", "response").type;
    return { kotlin: name, serializer: serializerOf({ ...target, nullable: false }), nullable: target.nullable };
  }

  operations(): OperationModel[] {
    const ops: OperationModel[] = [];
    for (const routePath of Object.keys(this.doc.paths ?? {}).sort()) {
      const item = this.doc.paths?.[routePath] ?? {};
      for (const method of METHODS) {
        const op = item[method];
        if (!isObject(op)) continue;
        ops.push(this.operation(routePath, method, op));
      }
    }
    return ops;
  }

  private operation(routePath: string, method: Method, op: Record<string, unknown>): OperationModel {
    const opName = operationName(method, routePath);
    const decls: Decl[] = [];

    let request: KType | undefined;
    const body = isObject(op.requestBody) && isObject(op.requestBody.content) ? op.requestBody.content["application/json"] : undefined;
    if (isObject(body) && isObject(body.schema)) {
      const result = this.typeOf(body.schema, `${opName}Request`, "", "request");
      decls.push(...result.decls);
      request = result.type;
    }

    let response: KType | undefined;
    let responseKind: OperationModel["responseKind"] = "None";
    let successStatus = 200;
    const responses = isObject(op.responses) ? op.responses : {};
    const success = Object.keys(responses).filter((s) => s.startsWith("2")).sort();
    if (success.length > 0) successStatus = Number(success[0]);
    for (const status of success) {
      const content = isObject(responses[status]) && isObject((responses[status] as Schema).content) ? ((responses[status] as Schema).content as Schema) : undefined;
      if (!content) continue;
      const json = content["application/json"];
      const stream = content["text/event-stream"];
      const chosen = isObject(json) ? json : isObject(stream) ? stream : undefined;
      if (chosen && isObject(chosen.schema)) {
        const result = this.typeOf(chosen.schema, `${opName}Response`, "", "response");
        decls.push(...result.decls);
        response = result.type;
        responseKind = isObject(json) ? "Json" : "EventStream";
        successStatus = Number(status);
        break;
      }
      if (Object.keys(content).length > 0) {
        responseKind = "Raw";
        successStatus = Number(status);
      }
    }

    const parameters = (Array.isArray(op.parameters) ? op.parameters : []).filter(isObject);
    const pathParams = parameters.filter((p) => p.in === "path").map((p) => String(p.name));
    for (const match of routePath.matchAll(/\{(\w+)\}/g)) {
      if (!pathParams.includes(match[1] ?? "")) pathParams.push(match[1] ?? "");
    }
    const queryParams = parameters.filter((p) => p.in === "query");
    let query: { name: string; params: QueryParam[] } | undefined;
    if (queryParams.length > 0) {
      const queryName = `${opName}Query`;
      const params: QueryParam[] = [];
      const props: PropDecl[] = [];
      const nested: Decl[] = [];
      for (const p of queryParams) {
        const jsonName = String(p.name);
        const { type, decls: inner } = this.typeOf(isObject(p.schema) ? p.schema : {}, pascal(jsonName), queryName, "request");
        nested.push(...inner);
        const kotlinName = camel(jsonName);
        props.push({ jsonName, kotlinName, type, required: p.required === true, doc: typeof p.description === "string" ? p.description : this.describe(isObject(p.schema) ? p.schema : {}) });
        params.push({ jsonName, kotlinName, type, required: p.required === true });
      }
      decls.push({ kind: "class", name: queryName, doc: `Query parameters of ${method.toUpperCase()} ${routePath}.`, context: "request", props, nested });
      query = { name: queryName, params };
    }

    return {
      opName,
      method,
      routePath,
      summary: typeof op.summary === "string" ? op.summary : undefined,
      description: typeof op.description === "string" ? op.description : undefined,
      request,
      response,
      responseKind,
      successStatus,
      pathParams,
      query,
      decls,
    };
  }
}

interface QueryParam {
  jsonName: string;
  kotlinName: string;
  type: KType;
  required: boolean;
}

interface OperationModel {
  opName: string;
  method: Method;
  routePath: string;
  summary?: string;
  description?: string;
  request?: KType;
  response?: KType;
  responseKind: "Json" | "EventStream" | "Raw" | "None";
  successStatus: number;
  pathParams: string[];
  query?: { name: string; params: QueryParam[] };
  decls: Decl[];
}

/** `GET /api/v1/workouts/{id}/sets` → `GetWorkoutsByIdSets`. Stable as long as the route is. */
export function operationName(method: string, routePath: string): string {
  const segments = routePath
    .replace(/^\/api\/v1\//, "")
    .split("/")
    .filter(Boolean)
    .map((segment) => {
      const param = /^\{(\w+)\}$/.exec(segment)?.[1];
      return param ? `By${pascal(param)}` : pascal(segment);
    });
  return pascal(method) + segments.join("");
}

function render(type: KType): string {
  return type.nullable ? `${type.kotlin}?` : type.kotlin;
}

function serializerOf(type: KType): string {
  return type.nullable ? `${type.serializer}.nullable` : type.serializer;
}

// ---------------------------------------------------------------------------
// Emitting Kotlin
// ---------------------------------------------------------------------------

function propertyLine(prop: PropDecl, context: Context, indent: string): string {
  const serialName = prop.kotlinName !== prop.jsonName ? `${indent}@SerialName(${quote(prop.jsonName)})\n` : "";
  const name = identifier(prop.kotlinName);
  let declaration: string;
  if (context === "request" && !prop.required && prop.type.nullable) {
    declaration = `val ${name}: Patch<${prop.type.kotlin}> = Patch.Absent`;
  } else if (!prop.required) {
    declaration = `val ${name}: ${prop.type.kotlin}? = null`;
  } else if (prop.type.nullable && context === "response") {
    declaration = `val ${name}: ${prop.type.kotlin}? = null`;
  } else {
    declaration = `val ${name}: ${render(prop.type)}`;
  }
  return `${kdoc(prop.doc, indent)}${serialName}${indent}public ${declaration},`;
}

function emitDecl(decl: Decl, indent: string): string {
  switch (decl.kind) {
    case "alias":
      return `${kdoc(decl.doc, indent)}${indent}public typealias ${decl.name} = ${render(decl.target)}\n`;
    case "enum": {
      const used = new Set<string>(["Unknown"]);
      const constants = decl.values.map((value) => {
        let constant = value === "" ? "Empty" : pascal(value);
        while (used.has(constant)) constant = `${constant}Value`;
        used.add(constant);
        return `${indent}    ${constant}(${quote(value)}),`;
      });
      return [
        kdoc(decl.doc, indent),
        `${indent}@Serializable(with = ${decl.name}.Serializer::class)\n`,
        `${indent}public enum class ${decl.name}(override val wireValue: String) : WireEnum {\n`,
        `${constants.join("\n")}\n`,
        `${indent}    /** A value this build does not know; never sent. */\n`,
        `${indent}    Unknown(""),\n`,
        `${indent}    ;\n\n`,
        `${indent}    internal object Serializer : WireEnumSerializer<${decl.name}>(${quote(decl.name)}, ${decl.name}.entries, Unknown)\n`,
        `${indent}}\n`,
      ].join("");
    }
    case "class": {
      const props = decl.props.map((p) => propertyLine(p, decl.context, `${indent}    `)).join("\n");
      const nested = decl.nested.map((n) => emitDecl(n, `${indent}    `)).join("\n");
      const body = nested ? ` {\n${nested}${indent}}` : "";
      return `${kdoc(decl.doc, indent)}${indent}@Serializable\n${indent}public data class ${decl.name}(\n${props}\n${indent})${body}\n`;
    }
  }
}

