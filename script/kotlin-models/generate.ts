/**
 * Generates the native app's API models (Kotlin, kotlinx.serialization) from
 * docs/openapi.json. See docs/mobile-app-plan.md, Phase 2.
 *
 * Output, one package (com.fitai.coach.core.api.generated):
 *  - a file per component schema (data class, enum or typealias);
 *  - a file per operation holding its inline request body, success response
 *    and query-parameter types;
 *  - ApiEndpoints.kt: one typed ApiEndpoint object per operation.
 *
 * Written in-repo rather than with OpenAPI Generator because the mapping
 * rules matter more than generality, and they are this API's:
 *  - enums decode unknown values as `Unknown` (WireEnumSerializer), so a
 *    server that adds a value cannot crash an installed build;
 *  - an optional AND nullable request field is a `Patch<T>`, so "leave it"
 *    and "clear it" stay distinct (153 of them, mostly on PATCH bodies);
 *  - zod-to-openapi's shapes: `allOf [ref, {nullable}]` is a nullable ref,
 *    `allOf [ref, {properties}]` is one merged class, and `oneOf`/`anyOf`
 *    (error unions, "any JSON") are raw `JsonElement`.
 * It needs no JVM to run, so CI regenerates and diffs it in the Node job.
 */

type Schema = Record<string, unknown>;

export interface OpenApiDocument {
  paths?: Record<string, Record<string, unknown>>;
  components?: { schemas?: Record<string, Schema> };
}

export const KOTLIN_PACKAGE = "com.fitai.coach.core.api.generated";
const RUNTIME_PACKAGE = "com.fitai.coach.core.api";
const HEADER = "// Generated by script/kotlin-models from docs/openapi.json. Do not edit: run `pnpm mobile:models`.";
const METHODS = ["get", "post", "put", "patch", "delete"] as const;
type Method = (typeof METHODS)[number];

type Context = "request" | "response";

/** A Kotlin type as referenced from a property or endpoint. */
interface KType {
  /** The type without nullability, e.g. `List<WorkoutLog>`. */
  readonly kotlin: string;
  /** An expression for its non-null serializer, e.g. `ListSerializer(WorkoutLog.serializer())`. */
  readonly serializer: string;
  readonly nullable: boolean;
}

interface PropDecl {
  readonly jsonName: string;
  readonly kotlinName: string;
  readonly type: KType;
  readonly required: boolean;
  readonly doc?: string;
}

type Decl =
  | { kind: "class"; name: string; doc?: string; context: Context; props: PropDecl[]; nested: Decl[] }
  | { kind: "enum"; name: string; doc?: string; values: string[] }
  | { kind: "alias"; name: string; doc?: string; target: KType };

const KOTLIN_KEYWORDS = new Set([
  "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface", "is",
  "null", "object", "package", "return", "super", "this", "throw", "true", "try", "typealias", "typeof",
  "val", "var", "when", "while",
]);

function isObject(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

function pascal(text: string): string {
  const words = text
    .replaceAll(/([a-z0-9])([A-Z])/g, "$1 $2")
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean);
  const joined = words.map((w) => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase()).join("");
  return /^[0-9]/.test(joined) ? `_${joined}` : joined || "Value";
}

function camel(text: string): string {
  if (/^[a-z][A-Za-z0-9]*$/.test(text)) return text;
  const p = pascal(text);
  return p.startsWith("_") ? p : p.charAt(0).toLowerCase() + p.slice(1);
}

function identifier(name: string): string {
  return KOTLIN_KEYWORDS.has(name) ? `\`${name}\`` : name;
}

function kdoc(text: string | undefined, indent: string): string {
  if (!text?.trim()) return "";
  const body = text
    .trim()
    .replaceAll("*/", "*&#47;")
    .split("\n")
    .map((line) => `${indent} * ${line}`.trimEnd())
    .join("\n");
  return `${indent}/**\n${body}\n${indent} */\n`;
}

function quote(value: string): string {
  return `"${value.replaceAll("\\", "\\\\").replaceAll('"', '\\"').replaceAll("$", "\\$")}"`;
}

