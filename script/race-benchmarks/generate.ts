/**
 * Offline HYROX benchmark generator.
 *
 * Streams the committed results CSV (default ./hyrox_results.csv, override with
 * --csv=PATH), cleans + aggregates it into per-cohort benchmarks and ranking
 * CDFs, and emits two committed, typed artifacts the predictor consumes:
 *   - shared/raceBenchmarks.generated.ts                       (small, shared)
 *   - server/services/racePrediction/raceRankingData.generated.ts (server-only)
 * plus a human summary at script/race-benchmarks/output/summary.md.
 *
 * Nothing here runs at build or request time — re-run manually after the CSV
 * changes: `pnpm data:race-benchmarks`.
 */
import { createReadStream } from "node:fs";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { parse } from "csv-parse";

import { HYROX_STATION_ORDER } from "../../shared/raceConstants";
import { aggregate, type CohortBenchmark, type ParsedRace, parseRaceRow } from "./lib";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const repoRoot = resolve(__dirname, "../..");

function log(...args: unknown[]): void {
  console.log("[race-benchmarks]", ...args);
}

function resolveCsvPath(): string {
  const arg = process.argv.find((a) => a.startsWith("--csv="))?.slice("--csv=".length);
  return arg ? resolve(arg) : resolve(repoRoot, "hyrox_results.csv");
}

const BENCHMARK_BANNER = `// GENERATED by script/race-benchmarks/generate.ts — DO NOT EDIT BY HAND.
// Regenerate: pnpm data:race-benchmarks  (reads ./hyrox_results.csv)
// Per-cohort median splits, run-leg fatigue curve, and transition time, derived
// from real HYROX singles results. Consumed by shared/raceSpec.ts.`;

const RANKING_BANNER = `// GENERATED by script/race-benchmarks/generate.ts — DO NOT EDIT BY HAND.
// Regenerate: pnpm data:race-benchmarks
// Per-cohort finish-time CDF (total_time at percentiles 1..99) for percentile
// ranking. Server-only — never imported by the client bundle.`;

function renderBenchmarkModule(
  benchmarks: Record<string, CohortBenchmark>,
  meta: Record<string, unknown>,
): string {
  return `${BENCHMARK_BANNER}

export interface CohortBenchmark {
  division: "open" | "pro";
  gender: "male" | "female";
  /** null for the division×gender (all-ages) roll-up. */
  ageGroup: string | null;
  sampleSize: number;
  /** Median split per station, keyed by HyroxStation. */
  stationP50Seconds: Record<string, number>;
  /** 8 per-run-leg medians (run_1..run_8) — the fatigue curve. */
  runLegP50Seconds: number[];
  /** Median total transition (roxzone) time. */
  transitionTotalP50Seconds: number;
}

export const RACE_BENCHMARKS: Record<string, CohortBenchmark> = ${JSON.stringify(benchmarks, null, 2)};

export const RACE_BENCHMARKS_META = ${JSON.stringify(meta, null, 2)} as const;
`;
}

function renderRankingModule(
  rankings: Record<string, { sampleSize: number; finishSecondsByPercentile: number[] }>,
): string {
  return `${RANKING_BANNER}

export interface CohortCdf {
  sampleSize: number;
  /** total_time at percentiles 1..99 (seconds), ascending. */
  finishSecondsByPercentile: number[];
}

export const RACE_RANKINGS: Record<string, CohortCdf> = ${JSON.stringify(rankings, null, 2)};
`;
}

function renderSummary(
  benchmarks: Record<string, CohortBenchmark>,
  meta: Record<string, unknown>,
  warnings: string[],
): string {
  const main = ["open|male", "open|female", "pro|male", "pro|female"].filter((k) => benchmarks[k]);
  const lines = [
    "# HYROX race-benchmark summary",
    "",
    `Generated: ${meta.generatedAt}`,
    `Source rows: ${meta.sourceRows} · usable singles rows: ${meta.usableRows} · cohorts emitted: ${meta.emittedCohorts} · age cohorts dropped (below sample gate): ${meta.ageCohortsDropped}`,
    "",
    "## Division × gender roll-ups",
    "",
    "| Cohort | n | run_1 | run_8 | transition | " + HYROX_STATION_ORDER.join(" | ") + " |",
    "| --- | ---: |" + " ---: |".repeat(3 + HYROX_STATION_ORDER.length),
  ];
  for (const key of main) {
    const b = benchmarks[key];
    const stations = HYROX_STATION_ORDER.map((s) => b.stationP50Seconds[s]).join(" | ");
    lines.push(
      `| ${key} | ${b.sampleSize} | ${b.runLegP50Seconds[0]} | ${b.runLegP50Seconds[7]} | ${b.transitionTotalP50Seconds} | ${stations} |`,
    );
  }
  lines.push(
    "",
    "All splits are median (p50) seconds. `run_1`/`run_8` show the fatigue curve; `transition` is the median total roxzone time the deterministic path now adds.",
    "",
    "## Sanity checks",
    warnings.length === 0
      ? "No physiology-order warnings (column→station mapping looks correct)."
      : warnings.map((w) => `- ⚠️ ${w}`).join("\n"),
    "",
  );
  return lines.join("\n");
}

/** Catch a transposed work_N→station mapping: farmers_carry should be the
 *  fastest loaded station, well under wall_balls and skierg. */
function physiologyWarnings(benchmarks: Record<string, CohortBenchmark>): string[] {
  const warnings: string[] = [];
  for (const [key, b] of Object.entries(benchmarks)) {
    const f = b.stationP50Seconds.farmers_carry;
    if (f >= b.stationP50Seconds.wall_balls || f >= b.stationP50Seconds.skierg) {
      warnings.push(
        `${key}: farmers_carry (${f}s) not faster than wall_balls/skierg — check work_N→station mapping.`,
      );
    }
  }
  return warnings;
}

async function main(): Promise<void> {
  const csvPath = resolveCsvPath();
  log(`Reading ${csvPath}`);

  const races: ParsedRace[] = [];
  let sourceRows = 0;

  const parser = createReadStream(csvPath).pipe(
    parse({ columns: true, skip_empty_lines: true, relax_column_count: true, trim: true }),
  );
  for await (const record of parser) {
    sourceRows++;
    const parsed = parseRaceRow(record as Record<string, string>);
    if (parsed) races.push(parsed);
  }

  log(`Parsed ${sourceRows} rows → ${races.length} clean singles results`);

  const { benchmarks, rankings, meta } = aggregate(races);
  const warnings = physiologyWarnings(benchmarks);
  for (const w of warnings) log(`WARNING: ${w}`);

  const fullMeta = {
    generatedAt: new Date().toISOString().slice(0, 10),
    sourceRows,
    usableRows: meta.usableRows,
    emittedCohorts: meta.emittedCohorts,
    ageCohortsDropped: meta.ageCohortsDropped,
    minCohortSample: 200,
  };

  const benchmarkPath = resolve(repoRoot, "shared/raceBenchmarks.generated.ts");
  const rankingPath = resolve(
    repoRoot,
    "server/services/racePrediction/raceRankingData.generated.ts",
  );
  const outDir = resolve(__dirname, "output");
  mkdirSync(outDir, { recursive: true });

  writeFileSync(benchmarkPath, renderBenchmarkModule(benchmarks, fullMeta));
  writeFileSync(rankingPath, renderRankingModule(rankings));
  writeFileSync(resolve(outDir, "summary.md"), renderSummary(benchmarks, fullMeta, warnings));

  log(`Wrote ${benchmarkPath}`);
  log(`Wrote ${rankingPath}`);
  log(`Wrote ${resolve(outDir, "summary.md")}`);
  log(
    `Cohorts: ${meta.emittedCohorts} (${meta.ageCohortsDropped} age cohorts below the ${fullMeta.minCohortSample}-row gate)`,
  );
}

try {
  await main();
} catch (err) {
  console.error(err);
  process.exit(1);
}
